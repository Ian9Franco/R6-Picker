export type OperatorPlayerStat = { matches: number; winRate: number; kd: number };

type PlayerStats = Record<string, OperatorPlayerStat>;

function parse(rows: string): PlayerStats {
  return Object.fromEntries(rows.trim().split("\n").map((row) => {
    const [name, matches, winRate, kd] = row.split("|");
    return [normalize(name), { matches: Number(matches), winRate: Number(winRate), kd: Number(kd) }];
  }));
}

function normalize(value: string): string {
  return value.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "").replace(/[^a-z0-9]/g, "");
}

